import importlib.util
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

if sys.version_info < (3, 9):
    sys.exit(f"Install failed: Python 3.9+ is required (found {sys.version_info.major}.{sys.version_info.minor}).")

WINDOWS = os.name == "nt"
if __name__ == "__main__" and WINDOWS and not sys.flags.utf8_mode:
    sys.exit(subprocess.run([sys.executable, "-X", "utf8", *sys.argv]).returncode)

# Import without writing bytecode, including during --dry-run.
sys.dont_write_bytecode = True

REPO = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("pm_setup", REPO / "mods/pm-dash/setup.py")
installer = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(installer)

# Keep the historical marker so layouts generated by install.sh and install.py are interchangeable.
GENERATED_BY = "dudu install.sh"
LAYOUT_NAME = "dudu"
LEGACY_LAYOUT_NAME = "pm"
# The dudu layout draws notifications with pm-toast, which hides dispatched workers' agent notices.
TOAST = "pm-toast"
TOAST_HINT = f'"toast": "{TOAST}"'
# The PM list sits right under the PM entry (pm-nav); the mod sizes its own block.
PM_LIST = {"id": "pm-list", "type": "block", "size": {"px": 30}, "content": {"mod": "pm-list"}}
HERDR_LISTS_ID = "herdr-lists"
HERDR_LISTS_ACTION = f"layout.toggle:{HERDR_LISTS_ID}"
HERDR_LISTS_KEY_SECTION = f"layout:{LAYOUT_NAME}"
PROJECT_SEARCH_ACTION = "pm-project.search"
PROJECT_SEARCH_TERMINAL_ACTION = "terminal"
# The project view: a column in the pm-stage stack with its title bar in a separate window_drag
# block above the selectable body block. Herdr's window_drag is node-level and ShellRoot paints
# TextSelectionLayer before mod content, so keeping window_drag on the header block alone lets
# the title bar move/maximize the window while the body keeps native TextView drag-selection.
PM_PROJECT_HEADER = {
    "id": "pm-project-header", "type": "block", "size": {"px": 56},
    "window_drag": True, "content": {"mod": "pm-project", "props": {"header": True}},
}
PM_PROJECT_BODY = {
    "id": "pm-project-body", "type": "block",
    "content": {"mod": "pm-project", "props": {"body": True}},
}
PM_PROJECT = {
    "id": "pm-project", "type": "column", "resizable": False,
    "children": [PM_PROJECT_HEADER, PM_PROJECT_BODY],
}
OLD_PM_PROJECT = {"id": "pm-project", "type": "block", "content": {"mod": "pm-project"}}
PM_BOARD = {"id": "pm-board", "type": "block", "window_drag": True, "content": {"mod": "pm-dash"}}
MODS = ("pm-dash", "pm-nav", "pm-list", "pm-toast", "pm-project")
# Mods an earlier build of this branch installed and this one does not: pm-agents, a copy of Herdr's agents
# list (pull request #2). Its block in a pm layout goes back to Herdr's own agents mod, and the mod is removed.
RETIRED = {"pm-agents": "agents"}
write_json, remove_path = installer.write_json, installer.remove_path
restore_windows_acl = installer.restore_windows_acl


def nodes(tree):
    if not isinstance(tree, dict):
        raise ValueError("layout nodes must be objects")
    yield tree
    children = tree.get("children", [])
    if not isinstance(children, list):
        raise ValueError("layout children must be arrays")
    for child in children:
        yield from nodes(child)


def ours(desktop, name):
    """The installed mods/<name> is the one this repository shipped (pm-agents: a clone of Herdr's agents with
    includePMs), not a mod of the person's own that has the same name."""
    folder = desktop / "mods" / name
    try:
        cloned = json.loads((folder / "mod.json").read_text(encoding="utf-8")).get("cloned_from") or {}
        return cloned.get("name") == "agents" and "includePMs" in (folder / "model.js").read_text(encoding="utf-8")
    except (OSError, ValueError, AttributeError):
        return False


def remove_retired_mods(desktop, args, prefix):
    for name in RETIRED:
        folder = desktop / "mods" / name
        if not (folder.exists() or folder.is_symlink()):
            continue
        if not ours(desktop, name):
            print(f"Keep {folder}: not the {name} mod this installer shipped.")
            continue
        print(f"{prefix}Remove {folder} (retired)")
        if not args.dry_run:
            remove_path(folder)


def restore_retired_blocks(desktop, tree):
    """Point blocks of retired mods back at the stock mods they replaced, unless the person has a mod of their own by
    that name installed. Returns the names it changed."""
    changed = []
    for node in nodes(tree):
        content = node.get("content")
        name = content.get("mod") if isinstance(content, dict) else None
        folder = desktop / "mods" / str(name)
        if name in RETIRED and not ((folder.exists() or folder.is_symlink()) and not ours(desktop, name)):
            changed.append(content["mod"])
            content["mod"] = RETIRED[content["mod"]]
    return changed


def has_mod(node, name):
    content = node.get("content")
    return node.get("id") == name or (isinstance(content, dict) and content.get("mod") == name)


def is_block(node, block):
    """The node is this installer's block: its id, type and mod, not only a matching id or mod."""
    content = node.get("content")
    return (node.get("id") == block["id"] and node.get("type") == block["type"]
            and isinstance(content, dict) and content.get("mod") == block["content"]["mod"])


def insert_pm_list(children):
    nav = [i for i, child in enumerate(children) if isinstance(child, dict) and has_mod(child, "pm-nav")]
    children.insert(nav[0] + 1 if nav else len(children), dict(PM_LIST, size=dict(PM_LIST["size"])))


def wrap_herdr_lists(tree, parent):
    """Wrap direct sibling `spaces` and `agents` blocks under `parent` into a default-hidden
    `herdr-lists` drawer column (Plan A), preserving all existing properties on those blocks.
    Returns True if the layout was mutated."""
    if parent is None or any(node.get("id") == HERDR_LISTS_ID for node in nodes(tree)):
        return False
    children = parent.get("children")
    if not isinstance(children, list):
        return False
    pm_list_idx = next((i for i, c in enumerate(children) if isinstance(c, dict) and has_mod(c, "pm-list")), -1)
    spaces_idx = next((i for i, c in enumerate(children) if isinstance(c, dict) and has_mod(c, "spaces")), -1)
    agents_idx = next((i for i, c in enumerate(children) if isinstance(c, dict) and has_mod(c, "agents")), -1)
    if spaces_idx < 0 or agents_idx < 0:
        return False
    # Leave legacy layouts where pm-list sits between spaces and agents untouched (user's arrangement).
    if pm_list_idx >= 0 and (spaces_idx < pm_list_idx or agents_idx < pm_list_idx):
        return False
    indices = sorted((spaces_idx, agents_idx))
    extracted = [children[i] for i in indices]
    for i in reversed(indices):
        children.pop(i)
    drawer = {
        "id": HERDR_LISTS_ID,
        "type": "column",
        "hidden": True,
        "size": {"weight": 1},
        "children": extracted,
    }
    children.insert(indices[0], drawer)
    if pm_list_idx >= 0:
        pm_list_node = next((c for c in children if isinstance(c, dict) and has_mod(c, "pm-list")), None)
        if pm_list_node is not None and isinstance(pm_list_node.get("size"), dict) and "px" in pm_list_node["size"]:
            pm_list_node["size"] = {"weight": 1}
    return True


def manual_layout(desktop, reason):
    print(f"Skip automatic layout: {reason}")
    print(f"Manual fallback (also in README.md): copy {desktop / 'layouts/main.json'} to {desktop / f'layouts/{LAYOUT_NAME}.json'}.")
    print('In sidebar-lists.children, insert first: {"id":"pm-nav","type":"block","size":{"px":64},"content":{"mod":"pm-nav"}}')
    print(f'and right after it: {json.dumps(PM_LIST, separators=(",", ":"))}')
    print('Replace the work column with: {"id":"pm-stage","type":"stack","active":"pm-board","children":[<original work node>,'
          + json.dumps(PM_BOARD, separators=(",", ":")) + ',' + json.dumps(PM_PROJECT, separators=(",", ":")) + ']}')
    print(f'At the root, add: {TOAST_HINT}')
    print("Keep the original work node intact; if main.json is missing, obtain the default layout from your Herdr desktop installation first.")


def back_up(target, args, prefix, label="layout"):
    if not target.exists():
        return
    layout_backup = target.with_name(f"{target.name}.pm-backup")
    if not layout_backup.exists():
        print(f"{prefix}Back up {label} to {layout_backup}")
        if not args.dry_run:
            shutil.copy2(target, layout_backup)
            restore_windows_acl(layout_backup)


def default_herdr_lists_key(platform=None):
    plat = sys.platform if platform is None else platform
    return "cmd-shift-e" if plat == "darwin" else "ctrl-shift-e"


def default_project_search_key(platform=None):
    plat = sys.platform if platform is None else platform
    return "cmd-k" if plat == "darwin" else "ctrl-k"


def _is_herdr_lists_action(action):
    if action == HERDR_LISTS_ACTION:
        return True
    if isinstance(action, dict):
        return (action.get("command") == "layout.toggle"
                and isinstance(action.get("args"), dict)
                and action["args"].get("id") == HERDR_LISTS_ID)
    return False


def _is_project_search_action(action):
    if action == PROJECT_SEARCH_ACTION:
        return True
    if isinstance(action, dict):
        return action.get("command") == PROJECT_SEARCH_ACTION
    return False


def _section_has_key(section, key):
    return isinstance(section, dict) and any(k.lower() == key.lower() for k in section)


def install_keys(desktop, args, prefix, platform=None):
    keys_path = desktop / "keys.json"
    if not keys_path.exists():
        print(f"Skip keys: {keys_path} does not exist yet.")
        return
    try:
        data = json.loads(keys_path.read_text(encoding="utf-8"))
        if not isinstance(data, dict):
            raise ValueError("keys.json root must be an object")
    except (OSError, ValueError) as error:
        print(f"Skip keys: cannot read {keys_path} ({error}).")
        return
    existing_section = data.get(HERDR_LISTS_KEY_SECTION)
    if existing_section is not None and not isinstance(existing_section, dict):
        print(f"Skip keys: {HERDR_LISTS_KEY_SECTION} in {keys_path} is not an object.")
        return

    changed = False

    def bind_layout_action(key, action, matcher):
        nonlocal changed
        for section in data.values():
            if isinstance(section, dict) and any(matcher(v) for v in section.values()):
                print(f"Skip keys: {keys_path} already binds {action}.")
                return False
        for sec_name in (HERDR_LISTS_KEY_SECTION, "global"):
            if _section_has_key(data.get(sec_name), key):
                print(f"Skip keys: {key} is already bound in {keys_path}; bind {action} manually if desired.")
                return False
        data.setdefault(HERDR_LISTS_KEY_SECTION, {})[key] = action
        print(f"{prefix}Bind {key} to {action} in {keys_path}")
        changed = True
        return True

    bind_layout_action(default_herdr_lists_key(platform), HERDR_LISTS_ACTION, _is_herdr_lists_action)
    search_key = default_project_search_key(platform)
    if bind_layout_action(search_key, PROJECT_SEARCH_ACTION, _is_project_search_action):
        term_sec = data.get("terminal")
        if term_sec is None or (isinstance(term_sec, dict) and not _section_has_key(term_sec, search_key)):
            data.setdefault("terminal", {})[search_key] = PROJECT_SEARCH_TERMINAL_ACTION
            print(f"{prefix}Bind {search_key} to {PROJECT_SEARCH_TERMINAL_ACTION} in terminal section of {keys_path}")

    if changed:
        back_up(keys_path, args, prefix, label="keys")
        if not args.dry_run:
            write_json(keys_path, data)
    elif not args.dry_run:
        restore_windows_acl(keys_path)


def uninstall_keys(desktop, args, prefix):
    keys_path = desktop / "keys.json"
    if not keys_path.exists():
        return
    try:
        data = json.loads(keys_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return
    if not isinstance(data, dict):
        return
    sec = data.get(HERDR_LISTS_KEY_SECTION)
    if not isinstance(sec, dict):
        return
    removed_herdr = [k for k, v in sec.items() if v == HERDR_LISTS_ACTION]
    removed_search = [k for k, v in sec.items() if v == PROJECT_SEARCH_ACTION]
    if not removed_herdr and not removed_search:
        return
    for k in removed_herdr + removed_search:
        del sec[k]
    if not sec:
        del data[HERDR_LISTS_KEY_SECTION]
    if removed_search:
        term_sec = data.get("terminal")
        if isinstance(term_sec, dict):
            for k in removed_search:
                if term_sec.get(k) == PROJECT_SEARCH_TERMINAL_ACTION:
                    del term_sec[k]
            if not term_sec:
                del data["terminal"]
    if removed_herdr:
        print(f"{prefix}Remove {HERDR_LISTS_ACTION} binding from {keys_path}")
    if removed_search:
        print(f"{prefix}Remove {PROJECT_SEARCH_ACTION} binding from {keys_path}")
    if not args.dry_run:
        write_json(keys_path, data)


def install_layout(desktop, args, prefix):
    target = desktop / f"layouts/{LAYOUT_NAME}.json"
    legacy = desktop / f"layouts/{LEGACY_LAYOUT_NAME}.json"
    source = desktop / "layouts/main.json"
    try:
        existing = None
        migrated_from = None
        if target.exists():
            candidate = json.loads(target.read_text(encoding="utf-8"))
            if any(has_mod(node, "pm-nav") for node in nodes(candidate)):
                existing = candidate
        elif legacy.exists():
            try:
                candidate = json.loads(legacy.read_text(encoding="utf-8"))
                if any(has_mod(node, "pm-nav") for node in nodes(candidate)):
                    existing = candidate
                    migrated_from = legacy
            except (OSError, ValueError, AttributeError):
                pass
        if existing is not None:
            mutated, hints = False, []
            if migrated_from is not None:
                print(f"{prefix}Migrate {migrated_from} to {target} (keeping {migrated_from} intact)")
            retired = restore_retired_blocks(desktop, existing)
            if retired:
                back_up(target, args, prefix)
                for name in retired:
                    print(f"{prefix}Show {RETIRED[name]} instead of {name} (retired) in {target}")
                mutated = True
            parent = next((node for node in nodes(existing)
                           if any(isinstance(child, dict) and has_mod(child, "pm-nav")
                                  for child in node.get("children", []))), None)
            has_list = any(has_mod(node, "pm-list") for node in nodes(existing))
            if not has_list and parent is None:
                # Never fall back to regenerating: that would replace the person's layout.
                print(f"Skip pm-list: no column in {target} holds pm-nav. Add this block by hand, "
                      f"right after pm-nav: {json.dumps(PM_LIST, separators=(',', ':'))}")
            elif not has_list:
                # A layout from before pm-list, the person's own edits included: add only the block.
                insert_pm_list(parent["children"])
                back_up(target, args, prefix)
                print(f"{prefix}Add the pm-list block to {target}")
                mutated = True
            elif parent is not None:
                kids = [child for child in parent["children"] if isinstance(child, dict)]
                at = next((i for i, child in enumerate(kids) if has_mod(child, "pm-list")), -1)
                if at > 0 and not has_mod(kids[at - 1], "pm-nav") and at + 1 < len(kids) and has_mod(kids[at + 1], "agents"):
                    # Where earlier installers put it. The block is the person's to place: say so, move nothing.
                    hints.append(f"The PM list now goes right under the PM entry. To have it there, "
                                 f"move the pm-list block right after pm-nav in {target}.")
            if wrap_herdr_lists(existing, parent):
                back_up(target, args, prefix)
                print(f"{prefix}Hide spaces and agents in {HERDR_LISTS_ID} drawer in {target}")
                mutated = True
            stage = next((node for node in nodes(existing) if node.get("id") == "pm-stage"
                          and node.get("type") == "stack" and isinstance(node.get("children"), list)), None)
            if stage is not None and not any(has_mod(node, "pm-project") for node in nodes(existing)):
                # A layout from before the project view: add only its column to the stack.
                stage["children"].append(copy.deepcopy(PM_PROJECT))
                back_up(target, args, prefix)
                print(f"{prefix}Add the pm-project block to {target}")
                mutated = True
            if stage is not None and stage.get("active") == "work" and any(
                    isinstance(child, dict) and child.get("id") == "pm-board" for child in stage["children"]):
                # Default pm-stage to pm-board (Projects) instead of bare terminal (work).
                stage["active"] = "pm-board"
                back_up(target, args, prefix)
                print(f"{prefix}Default pm-stage to pm-board in {target}")
                mutated = True
            boards = [node for node in nodes(existing) if "window_drag" not in node and is_block(node, PM_BOARD)]
            if boards:
                # Blocks from before the Projects page title bar moved the window: only pm-board gains the flag.
                for node in boards:
                    node["window_drag"] = True
                back_up(target, args, prefix)
                print(f"{prefix}Let the pm-board title bar move the window in {target}")
                mutated = True
            legacy_projects = [node for node in nodes(existing)
                               if is_block(node, OLD_PM_PROJECT) and not node["content"].get("props")]
            if legacy_projects:
                # Split legacy single-block pm-project into a window_drag header above the selectable body,
                # preserving any user-added keys (e.g. background, size, min) on the outer column node.
                for node in legacy_projects:
                    keep_drag = node.pop("window_drag", True) is not False
                    node.pop("content", None)
                    header = copy.deepcopy(PM_PROJECT_HEADER)
                    if not keep_drag:
                        header["window_drag"] = False
                    node["type"] = "column"
                    node.setdefault("resizable", False)
                    node["children"] = [header, copy.deepcopy(PM_PROJECT_BODY)]
                back_up(target, args, prefix)
                print(f"{prefix}Split pm-project into header and body blocks in {target}")
                mutated = True
            if "toast" not in existing:
                if existing.get("generated_by") == GENERATED_BY:
                    # A layout this installer generated before pm-toast existed.
                    existing["toast"] = TOAST
                    print(f"{prefix}Add {TOAST_HINT} to {target}")
                    mutated = True
                else:
                    hints.append(f"To hide finished-worker toasts, add {TOAST_HINT} at the root of {target}.")
            if not args.dry_run:
                if mutated:
                    write_json(target, existing)
                elif migrated_from is not None:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(migrated_from, target)
                    restore_windows_acl(target)
                elif target.exists():
                    restore_windows_acl(target)
            if not mutated and migrated_from is None:
                print(f"Skip layout: {target} already contains pm-nav.")
            if migrated_from is not None:
                hints.append(f"Kept {migrated_from} so a running {LEGACY_LAYOUT_NAME} layout stays undisturbed. "
                             f"After switching to {LAYOUT_NAME}, you may remove {migrated_from}.")
            for hint in hints:
                print(hint)
            return
        tree = json.loads(source.read_text(encoding="utf-8"))
        all_nodes = list(nodes(tree))
        sidebars = [node for node in all_nodes if node.get("id") == "sidebar-lists"]
        works = [node for node in all_nodes if node.get("id") == "work"]
        if (len(sidebars) != 1 or len(works) != 1
                or sidebars[0].get("type") != "column" or works[0].get("type") != "column"
                or "children" not in sidebars[0] or "children" not in works[0]
                or any(node.get("id") in ("pm-nav", "pm-list", "pm-stage", "pm-board", "pm-project", "pm-project-header", "pm-project-body") for node in all_nodes)):
            raise ValueError("expected one sidebar-lists column and one work column, without PM nodes")
        sidebar, work = sidebars[0], works[0]
        parents = [node for node in all_nodes if any(child is work for child in node.get("children", []))]
        if len(parents) != 1 or sidebar in list(nodes(work)) or work in list(nodes(sidebar)):
            raise ValueError("sidebar-lists and work must be separate branches")
        sidebar["children"].insert(0, {"id": "pm-nav", "type": "block", "size": {"px": 64}, "content": {"mod": "pm-nav"}})
        insert_pm_list(sidebar["children"])
        wrap_herdr_lists(tree, sidebar)
        children = parents[0]["children"]
        children[children.index(work)] = {"id": "pm-stage", "type": "stack", "active": "pm-board", "children": [
            work, copy.deepcopy(PM_BOARD), copy.deepcopy(PM_PROJECT)]}
    except (OSError, ValueError, AttributeError) as error:
        manual_layout(desktop, str(error))
        return
    tree["toast"] = TOAST
    tree["generated_by"] = GENERATED_BY
    if "version" in tree:
        tree["cloned_from"] = {"name": "main", "version": tree["version"]}
    layout_backup = target.with_name(f"{target.name}.pm-backup")
    if target.exists() and not layout_backup.exists():
        print(f"{prefix}Back up layout to {layout_backup}")
        if not args.dry_run:
            shutil.copy2(target, layout_backup)
            restore_windows_acl(layout_backup)
    print(f"{prefix}Generate {target} from {source}")
    if not args.dry_run:
        write_json(target, tree)


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="install.py",
        description="Install the PM skill for your coding agents and optional Herdr desktop mods.",
    )
    installer.add_agent_arguments(parser)
    parser.add_argument("--desktop", action="store_true", help="install desktop mods even if HERDR_APP_HOME is absent")
    parser.add_argument("--dry-run", action="store_true", help="print planned changes without writing files")
    parser.add_argument("--uninstall", action="store_true", help="remove PM hooks, skills, mods and layout; keep the ledger")
    args = parser.parse_args(argv)
    desktop = Path(os.environ.get("HERDR_APP_HOME") or Path.home() / ".config/herdr-app").expanduser().absolute()
    prefix = "Would " if args.dry_run else ""
    setup = installer.Setup(args, repo=REPO)

    setup.prepare()
    if args.uninstall:
        print(f'Before removing the {LAYOUT_NAME} layout, switch back: herdr-app do layout.switch \'{{"name":"main"}}\'')
        setup.save_settings()
        setup.remove_skill()
        layout_paths = [desktop / f"layouts/{LAYOUT_NAME}.json"]
        legacy_layout = desktop / f"layouts/{LEGACY_LAYOUT_NAME}.json"
        if legacy_layout.exists() or legacy_layout.is_symlink():
            layout_paths.append(legacy_layout)
        for path in (*(desktop / "mods" / name for name in MODS), *layout_paths):
            if path.exists() or path.is_symlink():
                if path in layout_paths:
                    try:
                        layout = json.loads(path.read_text(encoding="utf-8"))
                    except (OSError, ValueError) as error:
                        print(f"Keep layout {path}: cannot verify ownership ({error}).")
                        continue
                    if not isinstance(layout, dict) or layout.get("generated_by") != GENERATED_BY:
                        print(f"Keep layout {path}: not marked as generated by this installer.")
                        try:
                            retired = restore_retired_blocks(desktop, layout) if isinstance(layout, dict) else []
                        except ValueError:
                            retired = []
                        if retired:
                            # A block an earlier install of this branch pointed at pm-agents: its mod goes now.
                            for name in retired:
                                print(f"{prefix}Show {RETIRED[name]} instead of {name} (retired) in {path}")
                            if not args.dry_run:
                                write_json(path, layout)
                        continue
                print(f"{prefix}Remove {path}")
                if not args.dry_run:
                    remove_path(path)
            else:
                print(f"Skip removal: {path} is absent.")
        remove_retired_mods(desktop, args, prefix)
        uninstall_keys(desktop, args, prefix)
        setup.kept()
        return

    setup.install_skill()
    if desktop.exists() or args.desktop:
        for name in MODS:
            setup.copy_files(REPO / "mods" / name, desktop / "mods" / name,
                             ("gpui-kit.d.ts", "jsconfig.json", "*.test.mjs", "__pycache__", ".DS_Store"))
        remove_retired_mods(desktop, args, prefix)
        install_layout(desktop, args, prefix)
        install_keys(desktop, args, prefix)
        print(f'Next, select the {LAYOUT_NAME} layout: herdr-app do layout.switch \'{{"name":"{LAYOUT_NAME}"}}\'')
        print("Then click the PM board entry in the sidebar. If layout generation was skipped, finish the manual steps first.")
    else:
        print(f"Skip desktop: {desktop} does not exist; use --desktop to install it explicitly.")
    setup.save_settings()
    setup.finish()


