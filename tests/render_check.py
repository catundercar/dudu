RECORD = re.compile(r"^(\d{4}-\d\d-\d\dT\S+)\s+(TRACE|DEBUG|INFO|WARN|ERROR)\s+(\S+):\s(.*)$")

WRAPPER = r"""// Generated by tests/render_check.py in a private Herdr home; never installed.
// This mod's own main.js is main.real.js beside this file, unchanged.
import { View } from 'gpui-kit';
import { setShared, run, notify, nextCommand, watchFolder } from 'herdr';
import * as main from './main.real.js';
__IMPORTS__
export * from './main.real.js';
export default main.default;

// POKE: a folder of this run; a file written there re-renders every mod's view (cx.notify).
const MOD = __MOD__, ROLE = __ROLE__, POKE = __POKE__;
const STAGE = 'pm-stage', BOARD = 'pm-board', PROJECT = 'pm-project';
const say = text => console.log('[render-check] ' + text);
const failed = (what, e) => say(`ERROR ${MOD} ${what}: ${e?.message ?? e}\n${e?.stack ?? ''}`);

function wrap(cls, name) {
  const proto = cls.prototype;
  if (Object.prototype.hasOwnProperty.call(proto, '__renderCheck')) return;
  Object.defineProperty(proto, '__renderCheck', { value: name });
  for (const method of ['init', 'render']) {
    const real = proto[method];
    if (typeof real !== 'function') continue;
    proto[method] = function (...args) {
      let out;
      try { out = real.apply(this, args); } catch (e) { failed(`${name}.${method}`, e); throw e; }
      if (method === 'render') say(`R ${MOD} ${name}`);
      else if (name === 'default') { poke(args[1]); if (ROLE && !this.headerOnly) listen(this, args[1]); }
      return out;
    };
  }
}
for (const ns of [main, __NAMESPACES__]) {
  for (const [key, value] of Object.entries(ns)) {
    if (typeof value === 'function' && value.prototype instanceof View) wrap(value, ns === main && key === 'default' ? 'default' : key);
  }
}

function poke(cx) {
  cx.spawn(async cx => {
    try { for (;;) { await watchFolder(POKE); cx.notify(); } } catch (e) { failed('watching the poke folder', e); }
  });
}
function page(spec) {
  const at = spec.indexOf(':'), what = at < 0 ? spec : spec.slice(0, at), arg = at < 0 ? '' : spec.slice(at + 1);
  if (what === 'projects' || what === 'projects-board') {
    setShared('pm-dash', { view: what === 'projects' ? 'list' : 'board', project: '' });
    run('layout.select', { stack: STAGE, child: BOARD });
  } else if (what === 'chat') {
    setShared(PROJECT, { pm: arg });
    run('layout.select', { stack: STAGE, child: PROJECT });
  } else if (what === 'chat-remote') {
    // arg: "<machine>/<PM name>", a project as pm-list names one on another machine.
    setShared(PROJECT, { pm: arg, machine: arg.slice(0, arg.indexOf('/')) });
    run('layout.select', { stack: STAGE, child: PROJECT });
  } else if (what === 'board') {
    setShared('pm-dash', { view: 'board', project: arg });
    run('layout.select', { stack: STAGE, child: BOARD });
  } else if (what === 'toast') {
    notify({ title: 'render-check', body: 'pm-toast draws this notice', level: 'info', timeout: 20000 });
  } else throw new Error('unknown page ' + spec);
}
// pm-project's own fields, read for the report: when one is renamed, the report says null.
function report(view) {
  let found = null;
  try { found = typeof view.pm === 'function' ? Boolean(view.pm()) : null; } catch (_) { found = null; }
  return { pm: view.pmName ?? null, machine: view.machine ?? null, error: view.error ? String(view.error) : '',
    found, events: Array.isArray(view.events) ? view.events.length : null,
    detail: view.detail ?? null, thread: view.thread ?? null,
    threadTask: view.threadTask === undefined ? null : Boolean(view.threadTask),
    sessionTab: view.threadTab ?? null, sessionState: view.threadSessionState ?? null,
    sessionItems: Array.isArray(view.threadSession?.items) ? view.threadSession.items.length : null };
}
function listen(view, cx) {
  cx.spawn(async cx => {
    for (;;) {
      const command = await nextCommand();
      say(`CMD ${MOD} ${command}`);
      try {
        if (command.startsWith('rc-page:')) page(command.slice(8));
        else if (command.startsWith('rc-thread:')) view.openThread(command.slice(10), cx, { forceOpen: true });
        else if (command === 'rc-thread-session') {
          if (typeof view.selectThreadTab === 'function') view.selectThreadTab('session', cx);
        }
        else if (command === 'rc-expand-session-tools') {
          const held = view.threadSession;
          const ns = [main, __NAMESPACES__].find(x => x && typeof x.sessionTurns === 'function');
          if (held && Array.isArray(held.items) && ns) {
            for (const trn of ns.sessionTurns(held.items, { lang: view.lang })) {
              const toolPart = (trn.parts || []).find(p => p.kind === 'tools');
              if (toolPart) { (view.sessionToolsOpen ||= new Set()).add(toolPart.key); break; }
            }
          }
        }
        else if (command === 'rc-report') say(`STATE ${MOD} ` + JSON.stringify(report(view)));
      } catch (e) { failed(`command ${command}`, e); }
      cx.notify();
    }
  });
}
"""


# The window's size sets the pages' layout (pm-project's wide/narrow split). It is on screen only
# from its first frame until hide() hides the app (a second or two), flush in the main screen's
# bottom-left corner (corner() places it) where it is least in the way meanwhile.
WINDOW = [40.0, 40.0, 1000.0, 680.0]
# Drawn by each `herdr-app shot` (Check.frame); deleted at the end.
FRAME = "frame.png"
# The main screen's size and its display's UUID (window.json's "display"): without a display it
# knows, Herdr centers the window (src/place.rs), so the corner needs it. Computed here, not read
# from the person's window.json, which does not always name one.
SCREEN = r"""ObjC.import('AppKit'); const f = $.NSScreen.screens.objectAtIndex(0).frame;
ObjC.bindFunction('CGMainDisplayID', ['unsigned int', []]);
ObjC.bindFunction('CGDisplayCreateUUIDFromDisplayID', ['void *', ['unsigned int']]);
ObjC.bindFunction('CFUUIDCreateString', ['id', ['void *', 'void *']]);
const u = $.CGDisplayCreateUUIDFromDisplayID($.CGMainDisplayID());
JSON.stringify([f.size.width, f.size.height, u ? ObjC.unwrap($.CFUUIDCreateString(null, u)).toLowerCase() : null])"""
# Hides the private Herdr (NSRunningApplication.hide, like Cmd-H on it): never activates it, needs
# no Accessibility permission. Herdr activates itself after opening its window (`open -j` does
# not keep it hidden), so this runs once the window answers.
HIDE = r"""ObjC.import('AppKit'); const app = $.NSRunningApplication.runningApplicationWithProcessIdentifier(__PID__);
app.isNil() ? 'gone' : (app.hide ? 'hidden' : 'not hidden')"""
# Read-only: how many of one process's windows are on screen now.
SHOWN = r"""ObjC.import('CoreGraphics');
const all = ObjC.deepUnwrap(ObjC.castRefToObject($.CGWindowListCopyWindowInfo(0, 0))) || [];
String(all.filter(w => w.kCGWindowOwnerPID == __PID__ && w.kCGWindowLayer == 0 && w.kCGWindowIsOnscreen).length)"""


def jxa(script, timeout=10):
    """Runs a read-only (or own-app) JavaScript for Automation snippet; '' when it fails."""
    try:
        r = subprocess.run(["osascript", "-l", "JavaScript", "-e", script], capture_output=True, text=True, timeout=timeout)
    except (OSError, subprocess.SubprocessError):
        return ""
    return r.stdout.strip()


def corner():
    """window.json's place: WINDOW's size, flush in the main screen's bottom-left corner (top-left
    screen coordinates), on that display."""
    try:
        width, height, display = json.loads(jxa(SCREEN))
    except (ValueError, TypeError):
        return {"state": "windowed", "bounds": WINDOW}
    place = {"state": "windowed", "bounds": [0.0, float(height) - WINDOW[3], WINDOW[2], WINDOW[3]]}
    if isinstance(display, str) and display:
        place["display"] = display
    return place


class Blocked(Exception):
    """The check cannot run in isolation; nothing was judged."""


def clean_env(**extra):
    # No HC_* from the shell this runs in: inside a Herdr terminal they name the person's core.
    env = {k: v for k, v in os.environ.items() if not k.startswith("HC_") and k not in ("HERDR_APP_HOME", "PM_HOME")}
    env.update(extra)
    return env


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    tmp.replace(path)


def copy_plain(src, dst):
    """Folders and regular files only: no sockets, and no links that could lead writes back out."""
    dst.mkdir(parents=True, exist_ok=True)
    for entry in os.scandir(src):
        if entry.is_symlink() or entry.name in ("__pycache__", ".DS_Store"):
            continue
        if entry.is_dir():
            copy_plain(Path(entry.path), dst / entry.name)
        elif entry.is_file():
            shutil.copy2(entry.path, dst / entry.name)


def ledger_source():
    if os.environ.get("PM_HOME"):
        return Path(os.environ["PM_HOME"]).expanduser()
    canonical = Path.home() / ".dudu"
    default = Path.home() / ".claude/pm"
    if default.is_dir():
        try:
            if canonical.exists() and default.samefile(canonical):
                return canonical
        except OSError:
            pass
        return default
    return canonical


def frontmost():
    """The frontmost app's pid, read-only; None when it cannot be read."""
    r = subprocess.run(["osascript", "-l", "JavaScript", "-e",
                        "ObjC.import('AppKit'); $.NSWorkspace.sharedWorkspace.frontmostApplication.processIdentifier"],
                       capture_output=True, text=True, timeout=10)
    return int(r.stdout) if r.stdout.strip().isdigit() else None


def nap(seconds):
    time.sleep(seconds)


class Check:
    def __init__(self, args):
        self.args = args
        self.dir = Path(args.dir).expanduser().absolute() if args.dir else REPO / "evidence/render-check/run"
        self.app, self.ledger, self.src = self.dir / "app", self.dir / "ledger", self.dir / "src"
        self.log, self.shots, self.poke_dir = self.dir / "app.log", self.dir / "shots", self.dir / "poke"
        self.pokes = 0
        self.session = f"rc{os.getpid()}"
        self.pid = None
        self.core = False
        self.terminals = []
        self.exe = None
        self.launched = False
        self.front = None
        self.drawn = 0  # frames drawn on demand (not `frames`: scripts that extend Check use that name)
        self.unframed = ""  # why the last shot drew nothing, when it failed
        self.hidden = ""

    # --- the only two ways out to Herdr: this run's window, this run's core ---------------
    def herdr(self, *args, timeout=20):
        home = self.app.resolve()
        if not self.app.is_dir() or home == PERSON_HOME.resolve() or self.dir.resolve() not in home.parents:
            raise Blocked(f"refusing to call herdr-app outside this run's home ({self.app})")
        return subprocess.run(["herdr-app", *args], env=clean_env(HERDR_APP_HOME=str(self.app)),
                              capture_output=True, text=True, timeout=timeout)

    def hc(self, *args, timeout=30):
        return subprocess.run(["hc", *args], env=clean_env(HC_SESSION=self.session), capture_output=True, text=True,
                              timeout=timeout)

    def do(self, command):
        """Runs a command in this run's window; returns what went wrong, or ''."""
        r = self.herdr("do", command)
        if r.returncode != 0 or not re.search(r'"ok":\s*true', r.stdout):
            return f"herdr-app do {command}: {(r.stdout + r.stderr).strip()}"
        return ""

    # --- setup ---------------------------------------------------------------------------
    def prepare(self):
        if not shutil.which("herdr-app") or not shutil.which("hc"):
            raise Blocked("herdr-app and hc must be on PATH")
        if sys.platform != "darwin":
            raise Blocked("this check launches the macOS app bundle; other systems are not supported yet")
        sock = self.app / "herdr-app.sock"
        if len(str(sock).encode()) >= SUN_LEN:
            raise Blocked(f"{sock} is {len(str(sock).encode())} bytes, the socket path limit is {SUN_LEN - 1}; pass a shorter --dir")
        if self.dir.exists():
            if sock.exists() and self.herdr("status", timeout=5).returncode == 0:
                raise Blocked(f"a Herdr from an earlier run still uses {self.app}; quit it with "
                              f"HERDR_APP_HOME={self.app} herdr-app do app.quit")
            if any(self.dir.iterdir()) and not (self.dir / MARK).exists():
                raise Blocked(f"{self.dir} is not empty and not a render-check run folder; pick another --dir")
            shutil.rmtree(self.dir)
        self.dir.mkdir(parents=True)
        (self.dir / MARK).write_text("a tests/render_check.py run; deleted by the next run\n")
        self.shots.mkdir()
        self.poke_dir.mkdir()
        # The mods and layout under test.
        if self.args.rev:
            tar = subprocess.run(["git", "-C", str(REPO), "archive", self.args.rev, "mods", "layouts"], capture_output=True)
            if tar.returncode:
                raise Blocked(f"git archive {self.args.rev}: {tar.stderr.decode().strip()}")
            self.src.mkdir()
            subprocess.run(["tar", "-x", "-C", str(self.src)], input=tar.stdout, check=True)
        else:
            copy_plain(REPO / "mods", self.src / "mods")
            copy_plain(REPO / "layouts", self.src / "layouts")
        source = Path(self.args.ledger).expanduser() if self.args.ledger else ledger_source()
        if not (source / "tasks").is_dir():
            raise Blocked(f"no ledger at {source} (set PM_HOME or pass --ledger)")
        copy_plain(source, self.ledger)
        self.mods = sorted(p.name for p in (self.src / "mods").iterdir() if (p / "main.js").is_file())

    def choose(self):
        """The project and thread to show, from the ledger copy as pm.py sees it."""
        self.core = True  # pm.py asks hc; whatever core that starts is this run's and is stopped at the end.
        r = subprocess.run([sys.executable, str(self.src / "mods/pm-dash/skill/scripts/pm.py"), "state"], capture_output=True,
                           text=True, timeout=120, env=clean_env(HC_SESSION=self.session, PM_HOME=str(self.ledger)))
        try:
            state = json.loads(r.stdout)
        except ValueError:
            raise Blocked(f"pm.py state on the ledger copy did not print JSON: {(r.stderr or r.stdout)[-400:]}")
        tasks = state.get("tasks") or []
        def lines(pm):
            path = Path(pm.get("conversation") or "")
            try:
                return sum(1 for _ in path.open(encoding="utf-8")) if path.is_file() else 0
            except OSError:
                return 0
        pms = [pm for pm in state.get("pms") or [] if pm.get("name")]
        if self.args.pm:
            pms = [pm for pm in pms if pm["name"] == self.args.pm]
            if not pms:
                raise Blocked(f"no PM named {self.args.pm} in the ledger")
        # The busiest PM with a conversation: the project view's timeline needs rows to be tested at all.
        ranked = sorted(((lines(pm), sum(t.get("pm") == pm["name"] for t in tasks), pm) for pm in pms),
                        key=lambda x: (x[0] > 0, x[1], x[0]), reverse=True)
        if not ranked or ranked[0][0] == 0:
            raise Blocked("no PM in the ledger has a conversation to render (pass --ledger with one that does)")
        self.pm = ranked[0][2]
        own = [t for t in tasks if t.get("pm") == self.pm["name"] and (self.ledger / "tasks" / f"{t.get('id')}.json").is_file()]
        if self.args.thread:
            own = [t for t in own if t["id"] == self.args.thread]
        else:  # a review thread opens as the task it reviews (the views fold it in): not a page of its own
            own = [t for t in own if not t.get("review_of")]
        if not own:
            raise Blocked(f"{self.pm['name']} has no thread to open")
        self.thread = max(own, key=lambda t: t.get("updated") or "")["id"]
        self.project = self.pm.get("project") or re.sub(r"^pm-", "", self.pm["name"])
        for value in (self.pm["name"], self.thread):
            if not SAFE.match(value):
                raise Blocked(f"{value!r} cannot be passed in a command; pass --pm/--thread")
        self.session_thread = None
        proj_main = self.src / "mods/pm-project/main.js"
        if proj_main.is_file() and "selectThreadTab" in proj_main.read_text(encoding="utf-8"):
            pm_py = self.src / "mods/pm-dash/skill/scripts/pm.py"
            env = clean_env(HC_SESSION=self.session, PM_HOME=str(self.ledger))
            candidates = [t["id"] for t in sorted(own, key=lambda t: t.get("updated") or "", reverse=True)
                          if SAFE.match(t.get("id") or "") and t.get("context_tokens", 0) > 0]
            if not candidates and not self.args.thread:
                for p in sorted((self.ledger / "tasks").glob(f"{self.project}-*.json"),
                                key=lambda p: p.stat().st_mtime, reverse=True)[:25]:
                    if not p.stem.endswith("-review") and SAFE.match(p.stem):
                        candidates.append(p.stem)
            for tid in candidates:
                sr = subprocess.run([sys.executable, str(pm_py), "project", "session", tid, "--limit", "40"],
                                    capture_output=True, text=True, timeout=20, env=env)
                if sr.returncode == 0:
                    try:
                        if (json.loads(sr.stdout).get("items") or []):
                            self.session_thread = tid
                            break
                    except ValueError:
                        pass

    def install(self):
        version = subprocess.run(["herdr-app", "--version"], capture_output=True, text=True).stdout.split()[-1:]
        (self.app / "layouts").mkdir(parents=True)
        shutil.copy2(self.src / "layouts/pm.json", self.app / "layouts/pm.json")
        write_json(self.app / "settings.json", {"zoom": 1, "sounds": {"enabled": False}, "telemetry": False})
        # The app's own version as the last run: a first start after an update would update herdr-core.
        write_json(self.app / "update-notes.json", {"last_run": version[0] if version else "", "presented": version})
        write_json(self.app / "window.json", corner())
        write_json(self.app / "shared.json", {"layout": "pm", "frame.welcomed": "finished",
                                              PROJECT: {"pm": self.pm["name"]}, "pm-dash": {"view": "list", "project": ""}})
        for name in self.mods:
            src, dst = self.src / "mods" / name, self.app / "mods" / name
            copy_plain(src, dst)
            role = {DRIVER: "driver", PROJECT: "project"}.get(name, "")
            if role and "nextCommand" in (src / "main.js").read_text(encoding="utf-8"):
                raise Blocked(f"{name} now reads nextCommand() itself; the check's commands would take its keys. "
                              f"Pick another driver in tests/render_check.py")
            others = sorted(p.name for p in dst.glob("*.js") if p.name != "main.js" and ".test." not in p.name)
            (dst / "main.js").rename(dst / "main.real.js")
            text = (WRAPPER.replace("__IMPORTS__", "\n".join(f"import * as m{i} from './{n}';" for i, n in enumerate(others)))
                    .replace("__NAMESPACES__", ", ".join(f"m{i}" for i in range(len(others))))
                    .replace("__MOD__", json.dumps(name)).replace("__ROLE__", json.dumps(role))
                    .replace("__POKE__", json.dumps(str(self.poke_dir))))
            (dst / "main.js").write_text(text.replace("[main, ]", "[main]"), encoding="utf-8")

    def start(self):
        # Stand-ins, so the views draw their online states: a PM and the thread's worker, each `cat`.
        for name, label in (("rc-pm", f"pm={self.project}"), ("rc-worker", f"task={self.thread}")):
            r = self.hc("run", "--bg", "--no-parent", "--name", name, "--label", label, "--cwd", str(REPO), "cat")
            if r.returncode:
                raise Blocked(f"hc run in session {self.session}: {(r.stderr or r.stdout).strip()}")
            self.terminals.append(name)
        binary = Path(os.path.realpath(shutil.which("herdr-app")))
        bundle = binary.parents[2] if len(binary.parents) > 2 else binary
        if bundle.suffix != ".app":
            raise Blocked(f"herdr-app is not inside an app bundle ({binary})")
        self.exe = binary.name
        before = set(self.pids())
        self.front = frontmost()
        self.log.touch()
        cmd = ["open", "-g", "-n", "-a", str(bundle), "--stdout", str(self.log), "--stderr", str(self.log)]
        for key, value in {"HERDR_APP_HOME": self.app, "PM_HOME": self.ledger, "HC_SESSION": self.session,
                           "HERDR_TELEMETRY": "0", "DO_NOT_TRACK": "1", "RUST_LOG": "info"}.items():
            cmd += ["--env", f"{key}={value}"]
        self.launched = True
        subprocess.run(cmd, env=clean_env(), check=True)
        deadline = time.time() + 30
        while time.time() < deadline and not self.pid:
            self.pid = next((p for p in self.pids() if p not in before and self.ours(p)), None)
            nap(0.3)
        while time.time() < deadline:
            r = self.herdr("status", timeout=5)
            if r.returncode == 0:
                try:
                    if json.loads(r.stdout).get("layout") == "pm":
                        self.hide()
                        return self.drawing()
                except ValueError:
                    pass
            nap(0.2)  # often: the sooner it answers, the sooner it is hidden
        raise Blocked(f"the private Herdr did not answer within 30 s (log: {self.log})")

    def hide(self, wait=5):
        """Hides the private Herdr, and waits until none of its windows is on screen."""
        self.hidden = "not hidden"
        if not self.pid:
            return
        started, deadline = time.time(), time.time() + wait
        while time.time() < deadline:
            jxa(HIDE.replace("__PID__", str(int(self.pid))))
            nap(0.2)
            if jxa(SHOWN.replace("__PID__", str(int(self.pid)))) == "0":
                self.hidden = f"hidden {time.time() - started:.1f} s after it answered"
                return
        self.hidden = f"still on screen {wait} s after it answered"

    def on_screen(self):
        """Whether a window of the private Herdr is on screen now (read-only); None when unknown."""
        n = jxa(SHOWN.replace("__PID__", str(int(self.pid)))) if self.pid else ""
        return int(n) > 0 if n.isdigit() else None

    def drawing(self, wait=8):
        """A window that draws no frames renders no mod: then nothing can be judged. The
        sidebar's pm-list must render again after a poke (and the frame it draws)."""
        mark, deadline = self.log.stat().st_size, time.time() + wait
        while time.time() < deadline:
            self.poke()
            nap(0.3)
            if self.renders(DRIVER, mark):
                return
        raise Blocked(f"the private window draws no frames ({DRIVER} did not render again within {wait} s): "
                      + (self.unframed or "herdr-app shot answered, but no mod rendered"))

    def pids(self):
        r = subprocess.run(["pgrep", "-x", self.exe or "Herdr"], capture_output=True, text=True)
        return [int(p) for p in r.stdout.split()]

    def ours(self, pid):
        env = subprocess.run(["ps", "eww", "-p", str(pid)], capture_output=True, text=True).stdout
        return bool(re.search(rf"\bHC_SESSION={re.escape(self.session)}(\s|$)", env)
                    and f"HERDR_APP_HOME={self.app}" in env)

    # --- reading the log -------------------------------------------------------------------
    def records(self, since=0):
        with self.log.open("rb") as f:
            f.seek(since)
            text = ANSI.sub("", f.read().decode("utf-8", "replace"))
        out = []
        for line in text.splitlines():
            m = RECORD.match(line)
            if m:
                out.append({"level": m[2], "target": m[3], "text": m[4]})
            elif out and line.strip():
                out[-1]["text"] += "\n" + line
        return out

    def renders(self, mod, since, name="default"):
        return sum(1 for r in self.records(since) if r["text"] == f"{TAG} R {mod} {name}")

    def report(self):
        mark = self.log.stat().st_size
        self.do(f"{PROJECT}.rc-report")
        deadline = time.time() + 5
        while time.time() < deadline:
            for r in self.records(mark):
                if r["text"].startswith(f"{TAG} STATE {PROJECT} "):
                    return json.loads(r["text"].split(" ", 3)[3])
            nap(0.2)
        return None

    # --- the pages ---------------------------------------------------------------------------
    def poke(self):
        """Every mod's view renders again: the wrappers watch this folder and notify, and
        frame() draws the frame that renders them."""
        self.pokes += 1
        (self.poke_dir / "poke").write_text(str(self.pokes))
        nap(0.3)  # the wrappers' watchFolder wakes and calls cx.notify()
        self.frame()

    def frame(self):
        """Draws one frame now, whether or not the window can be seen. Returns what went wrong, or ''."""
        return self.shoot(self.dir / FRAME)

    def shoot(self, path, timeout=30):
        """`herdr-app shot`: draws the dirty window (window.draw), renders it offscreen and saves it.
        A shot that fails or does not answer is not a mod's error: the window did not draw, and
        the step it was for is not judged (exit 2). Returns what went wrong, or ''."""
        try:
            r = self.herdr("shot", str(path), timeout=timeout)
        except subprocess.TimeoutExpired:
            self.unframed = f"herdr-app shot did not answer within {timeout} s"
            return self.unframed
        answer = (r.stdout + r.stderr).strip()
        self.unframed = "" if r.returncode == 0 and '"error"' not in r.stdout else f"herdr-app shot: {answer[-300:]}"
        self.drawn += not self.unframed
        return self.unframed

    def touch_ledger(self):
        """A real change in the ledger copy, for the mods' folder watches: the thread's `updated`."""
        path = self.ledger / "tasks" / f"{self.thread}.json"
        if path.is_symlink() or self.ledger.resolve() not in path.resolve().parents:
            raise Blocked(f"{path} is not inside the ledger copy")
        task = json.loads(path.read_text(encoding="utf-8"))
        task["updated"] = time.strftime("%Y-%m-%d %H:%M:%S")
        write_json(path, task)

    def step(self, name, commands, mod, ready=None, wait=20):
        """Shows a page (commands: strings for `herdr-app do`, or callables), changes the ledger
        once, then re-renders every mod (the poke folder) until the page's mod has rendered 3
        times since it was shown and, for pm-project, its report shows the page's content."""
        mark, problems = self.log.stat().st_size, []
        for command in commands:
            problem = command() if callable(command) else self.do(command)
            if problem:
                problems.append(problem)
            nap(0.8)
        self.touch_ledger()
        state, deadline, pokes = None, time.time() + wait, 0
        while True:
            nap(0.7)
            self.poke()
            pokes += 1
            count = self.renders(mod, mark)
            if ready:
                state = self.report()
            done = pokes >= 2 and count >= 3 and (not ready or (state is not None and ready(state)))
            # Three pokes and not even the sidebar rendered: the window stopped drawing.
            if done or time.time() > deadline or (pokes >= 3 and not self.renders(DRIVER, mark)):
                break
        unshot = self.shoot(self.shots / f"{name}.png")
        count = self.renders(mod, mark)
        if unshot or not self.still_drawing():
            # The sidebar does not render either: the window stopped drawing, the page was not judged.
            return {"name": name, "mod": mod, "renders": count, "state": state, "stalled": True,
                    "problems": ["the window stopped drawing during this step: "
                                 + (unshot or self.unframed or "herdr-app shot answered, but the sidebar did not render")]}
        failing, _ = self.errors(mark)
        if failing:
            problems.append(f"{len(failing)} error(s) from the mods while this page was shown (listed below)")
        if count < 3:
            problems.append(f"{mod} rendered {count} time(s) after the page was shown, expected at least 3")
        if ready and not (state is not None and ready(state)):
            problems.append(f"{mod} did not reach the page's state: {json.dumps(state, ensure_ascii=False)}")
        return {"name": name, "mod": mod, "renders": count, "state": state, "stalled": False, "problems": problems}

    def still_drawing(self, wait=3):
        mark, deadline = self.log.stat().st_size, time.time() + wait
        self.poke()
        while time.time() < deadline:
            if self.renders(DRIVER, mark):
                return True
            nap(0.3)
            self.frame()  # frames come only from shots: a poke noticed late still gets drawn
        return bool(self.renders(DRIVER, mark))

    def project_shown(self, wait=10):
        """pm-project is built anew each time its page is shown, and learns its project when it
        renders (pmName): draw, and wait until it answers with its project."""
        deadline = time.time() + wait
        while time.time() < deadline:
            self.poke()  # and a frame: no render, no project
            state = self.report()
            if state and state.get("found"):
                return ""
            nap(0.2)
        return f"{PROJECT} did not show {self.pm['name']} within {wait} s"

    def session_shown(self, wait=10):
        """Draws until pm-project has loaded the session transcript on its Conversation tab."""
        deadline = time.time() + wait
        while time.time() < deadline:
            self.poke()
            state = self.report()
            if state and state.get("sessionTab") == "session" and state.get("sessionState") == "ready":
                return ""
            nap(0.2)
        return f"{PROJECT} did not load session for {self.session_thread} within {wait} s"

    def pages(self):
        pm, thread = self.pm["name"], self.thread
        page = lambda spec: f"{DRIVER}.rc-page:{spec}"
        plan = [
            ("projects", [page("projects")], "pm-dash", None),
            ("projects-board", [page("projects-board")], "pm-dash", None),
            ("conversation", [page(f"chat:{pm}")], PROJECT,
             lambda s: s.get("pm") == pm and s.get("found") is True and (s.get("events") or 0) > 0),
            ("project-board", [page(f"board:{pm}")], "pm-dash", None),
            ("thread", [page(f"chat:{pm}"), self.project_shown, f"{PROJECT}.rc-thread:{thread}"], PROJECT,
             lambda s: s.get("detail") is True and s.get("thread") == thread and s.get("threadTask") is True),
            *([("thread-session",
                [page(f"chat:{pm}"), self.project_shown, f"{PROJECT}.rc-thread:{self.session_thread}",
                 f"{PROJECT}.rc-thread-session", self.session_shown, f"{PROJECT}.rc-expand-session-tools"],
                PROJECT,
                lambda s: s.get("detail") is True and s.get("thread") == self.session_thread
                and s.get("sessionTab") == "session" and s.get("sessionState") == "ready"
                and (s.get("sessionItems") or 0) > 0)] if self.session_thread else []),
            # A project on a machine this private core does not know: the project page (never its
            # terminal) says it cannot read it there, and renders on without errors.
            ("remote-unreachable", [page(f"chat-remote:{UNREACHABLE}/{pm}")], PROJECT,
             lambda s: s.get("pm") == f"{UNREACHABLE}/{pm}" and s.get("machine") == UNREACHABLE
             and s.get("found") is False and bool(s.get("error"))),
            ("toast", [page("toast")], "pm-toast", None),
        ]
        steps = []
        for name, commands, mod, ready in plan:
            steps.append(self.step(name, commands, mod, ready))
            if steps[-1]["stalled"]:
                break  # The rest would only wait on a window that does not draw.
        return steps

    # --- the verdict -------------------------------------------------------------------------
    def tidy(self, text):
        """Paths as in the repo: the wrapper's own frames out, main.real.js is the mod's main.js."""
        lines = [line for line in text.splitlines()
                 if not re.search(r"/main\.js(\?v=\d+)?:\d+:\d+\)$|at apply \(native\)$", line)]
        text = re.sub(r"\?v=\d+", "", "\n".join(lines))
        return text.replace(f"{self.app}/", "").replace("main.real.js", "main.js").replace(str(Path.home()), "~")

    def errors(self, since=0):
        """Exceptions from the mods (the wrapper's ERROR lines, Herdr's own ERROR lines from scripts),
        and the check's commands Herdr did not deliver. Other warnings are listed, not judged."""
        failing, other = [], []
        for r in self.records(since):
            text = r["text"]
            if text.startswith(f"{TAG} ERROR "):
                failing.append(text[len(TAG) + 1:])
            elif r["level"] == "ERROR" and r["target"].startswith("gpui_shell"):
                failing.append(f"{r['target']}: {text}")
            elif r["level"] == "WARN" and re.search(r'unknown command "[\w-]+\.rc-', text):
                failing.append(f"not delivered (the mod was not alive): {text}")
            elif r["level"] in ("WARN", "ERROR"):
                other.append(f"{r['level']} {r['target']}: {text}")
        return [self.tidy(e) for e in failing], [self.tidy(e) for e in other]

    def judge(self, steps):
        """(exit code, report lines): 1 when a mod failed, 2 when the window stopped drawing and
        no mod failed (not judged), 0 otherwise."""
        lines, failed = [], False
        for s in steps:
            mark = "----" if s["stalled"] else "FAIL" if s["problems"] else "ok  "
            failed |= bool(s["problems"]) and not s["stalled"]
            lines.append(f"{mark} {s['name']:<15} {s['mod']} rendered {s['renders']}x" +
                         (f"  {json.dumps(s['state'], ensure_ascii=False)}" if s["state"] else ""))
            lines += [f"       {p}" for p in s["problems"]]
        front = frontmost()
        if self.front and front and front != self.front:
            lines.append(f"note: the frontmost app changed during the run (pid {self.front} -> {front}"
                         f"{', the private Herdr' if front == self.pid else ''})")
        else:
            lines.append(f"frontmost app: pid {self.front} before the run, pid {front} at the end; "
                         f"private window {self.hidden or 'not hidden'}, {self.drawn} frames drawn on demand")
        if self.on_screen():
            lines.append("note: the private window is on screen again at the end (something showed the app)")
        status = self.herdr("status", timeout=10)
        try:
            loaded = json.loads(status.stdout).get("errors") or []
        except ValueError:
            loaded = [f"herdr-app status: {(status.stdout + status.stderr).strip()}"]
        stalled = [s["name"] for s in steps if s["stalled"]]
        unseen = [m for m in self.mods if self.renders(m, 0) == 0] if not stalled else []
        failing, other = self.errors()
        if loaded:
            failed = True
            lines.append("FAIL herdr-app status errors:")
            lines += [f"       {json.dumps(e, ensure_ascii=False)}" for e in loaded]
        if unseen:
            failed = True
            lines.append(f"FAIL never rendered: {', '.join(unseen)}")
        if failing:
            failed = True
            lines.append(f"FAIL {len(failing)} error(s) from the mods:")
            for e in dict.fromkeys(failing):
                count = failing.count(e)
                lines.append("  " + e.replace("\n", "\n    ") + (f"   (x{count})" if count > 1 else ""))
        if other:
            lines.append(f"note: {len(other)} other warning(s) in the log (not judged):")
            lines += ["  " + o.splitlines()[0][:200] for o in dict.fromkeys(other)]
        if stalled and not failed:
            lines.append(f"NOT JUDGED: the window stopped drawing during {', '.join(stalled)}")
            return 2, lines
        return (1 if failed else 0), lines

    # --- cleanup -----------------------------------------------------------------------------
    def close(self):
        notes = []
        try:
            if (self.app / "herdr-app.sock").exists():
                self.herdr("do", "app.quit", timeout=10)
        except Exception as e:  # noqa: BLE001 - keep cleaning up
            notes.append(f"app.quit: {e}")
        if self.launched and not self.pid:
            # Stopped before the window was found: look for it once more, it may still be starting.
            deadline = time.time() + 10
            while time.time() < deadline and not self.pid:
                self.pid = next((p for p in self.pids() if self.ours(p)), None)
                nap(0.5)
            if self.pid and (self.app / "herdr-app.sock").exists():
                try:
                    self.herdr("do", "app.quit", timeout=10)
                except Exception as e:  # noqa: BLE001 - keep cleaning up
                    notes.append(f"app.quit: {e}")
        if self.pid:
            deadline = time.time() + 10
            while time.time() < deadline and self.alive(self.pid):
                nap(0.3)
            if self.alive(self.pid) and self.ours(self.pid):
                os.kill(self.pid, signal.SIGTERM)
                notes.append(f"the private Herdr ({self.pid}) did not quit; sent SIGTERM")
        if self.core:
            for name in self.terminals:
                self.hc("kill", name)
            self.hc("server", "stop")
            state = Path(os.environ.get("XDG_STATE_HOME") or Path.home() / ".local/state") / "herdr-core" / self.session
            if self.session.startswith("rc") and state.is_dir():
                shutil.rmtree(state, ignore_errors=True)
        if not self.args.keep:
            for path in (self.app, self.ledger, self.src, self.poke_dir):
                shutil.rmtree(path, ignore_errors=True)
            (self.dir / FRAME).unlink(missing_ok=True)
        return notes

    @staticmethod
    def alive(pid):
        try:
            os.kill(pid, 0)
            return True
        except ProcessLookupError:
            return False
        except PermissionError:
            return True


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--rev", help="check this commit's mods/ and layouts/ (default: the working tree)")
    parser.add_argument("--pm", help="the PM whose project to show (default: the busiest with a conversation)")
    parser.add_argument("--thread", help="the task whose detail to open (default: that PM's latest)")
    parser.add_argument("--ledger", help="ledger to copy (default: $PM_HOME, ~/.claude/pm or ~/.dudu)")
    parser.add_argument("--dir", help="run folder (default: evidence/render-check/run; keep the socket path short)")
    parser.add_argument("--keep", action="store_true", help="keep the private app home, ledger copy and sources")
    args = parser.parse_args()

    def stop(signum, _frame):
        raise KeyboardInterrupt(f"signal {signum}")
    for sig in (signal.SIGINT, signal.SIGTERM, signal.SIGHUP):
        signal.signal(sig, stop)

    started = time.time()
    check, code, lines = Check(args), 2, []
    try:
        check.prepare()
        check.choose()
        check.install()
        check.start()
        code, lines = check.judge(check.pages())
    except Blocked as e:
        lines = [f"BLOCKED {e}"]
    except subprocess.TimeoutExpired as e:
        # The private Herdr or its core stopped answering: nothing judged (exit 2), not a mod's error.
        lines = [f"BLOCKED {' '.join(map(str, e.cmd[:3]))} did not answer within {e.timeout:.0f} s"]
    except KeyboardInterrupt as e:
        lines = [f"interrupted ({e})"]
    finally:
        notes = check.close()
    what = f"rev {args.rev}" if args.rev else "working tree"
    head = [f"render-check: {what}, {len(getattr(check, 'mods', []))} mods, "
            f"project {getattr(check, 'pm', {}).get('name', '?')}, thread {getattr(check, 'thread', '?')}, "
            f"{time.time() - started:.0f} s"]
    tail = [f"note: {n}" for n in notes] + [f"log and shots: {check.dir}", "PASS" if code == 0 else "FAILED" if code == 1 else "NOT RUN"]
    out = "\n".join(head + lines + tail)
    print(out)
    if check.dir.is_dir():
        (check.dir / "report.txt").write_text(out + "\n", encoding="utf-8")
    return code


if __name__ == "__main__":
    sys.exit(main())
